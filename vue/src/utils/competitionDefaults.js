export function createDefaultCompetitionHelpItems (paperType, host) {
  const normalized = String(paperType || '').trim().toUpperCase()
  const paper = /^[A-Z]$/.test(normalized) ? normalized : 'A'
  const root = `http://${host}/dataset/${paper}`
  return [
    { left: `${root}/u1.tar.gz`, right: '数据集地址' },
    { left: `${root}/01.jpg`, right: '数据增强亮度' },
    { left: `${root}/02.jpg`, right: '数据增强灰度' },
    { left: `${root}/Augmentation.py`, right: '数据增强程序' }
  ]
}

export function formatCompetitionHelpContent (items) {
  return (items || []).map((item, index) => `${index + 1}. ${item.right}\n${item.left}`).join('\n\n')
}
