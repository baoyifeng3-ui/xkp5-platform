const assert = require('assert')
const fs = require('fs')

const admin = fs.readFileSync('src/views/management/ResourceManagement.vue', 'utf8')
const user = fs.readFileSync('src/views/user/ResourceCenter.vue', 'utf8')
const browser = fs.readFileSync('src/components/resources/ResourceBrowser.vue', 'utf8')
const upload = fs.readFileSync('src/components/resources/ResourceUploadDialog.vue', 'utf8')
const api = fs.readFileSync('src/api/ResourceSpaces.js', 'utf8')

for (const label of ['课程资源库', '公共资源库', '交换空间', '作业空间']) assert.ok(admin.includes(label))
for (const label of ['公共资源库', '交换空间', '作业空间']) assert.ok(user.includes(label))
assert.ok(!user.includes('课程资源库'))
assert.ok(admin.includes('一键清空'))
assert.ok(admin.includes('homeworkSummary'))
assert.ok(browser.includes('breadcrumbs'))
assert.ok(browser.includes('新建目录'))
assert.ok(browser.includes('下载'))
assert.ok(browser.includes('删除'))
assert.ok(api.includes('onUploadProgress'))
assert.ok(upload.includes('<el-progress'))
assert.ok(upload.includes('uploading'))
assert.ok(upload.includes('item.progress'))
assert.match(upload, /response\s*&&\s*\(response\.msg\s*\|\|\s*response\.message\)/)
assert.ok(!upload.includes("error&&error.message||'上传失败'"))
assert.ok(api.includes('admin/resource-spaces'))
assert.ok(api.includes('user/resource-spaces'))
assert.ok(api.includes('confirm: true'))

console.log('resource spaces UI contract tests passed')
