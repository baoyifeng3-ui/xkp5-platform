const assert = require('assert')
const fs = require('fs')

const router = fs.readFileSync('src/router/index.js', 'utf8')
const api = fs.readFileSync('src/api/License.js', 'utf8')
const diagnostics = fs.readFileSync('src/views/operations/LicenseDiagnostics.vue', 'utf8')

assert.match(router, /path:\s*["']license["']/, 'missing management license child route')
assert.match(router, /name:\s*["']PlatformLicense["']/, 'missing PlatformLicense route name')
assert.ok(api.includes("url: 'admin/license/status'"), 'missing license status API')
assert.ok(api.includes("responseType: 'blob'"), 'request download must use blob response')
for (const label of ['授权单位', '授权期限', '剩余天数', '授权导入时间']) assert.ok(diagnostics.includes(label), `missing user-facing field: ${label}`)
for (const internal of ['安装实例', '主机指纹', '公钥标识', '关联编号']) assert.ok(!diagnostics.includes(internal), `internal field should be hidden: ${internal}`)
assert.ok(diagnostics.includes('下载 .xkpreq'), 'diagnostics must expose request download')
assert.ok(diagnostics.includes('导入授权'), 'diagnostics must expose license import')
assert.ok(diagnostics.includes('createLicenseRequest'), 'diagnostics must use existing license APIs')
console.log('license navigation tests passed')
