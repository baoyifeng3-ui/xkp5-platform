const assert = require('assert')
const fs = require('fs')
const source = path => fs.readFileSync(path, 'utf8')
const router = source('src/router/index.js')
const view = source('src/views/operations/ImageRegistryView.vue')
const upload = source('src/components/operations/ImageUploadDialog.vue')
const deployment = source('src/components/operations/ImageDeploymentDialog.vue')
const service = source('src/services/imageRegistry.js')

assert.ok(/path:\s*["']image-registry["']/.test(router), 'registry route must remain registered')
assert.ok(service.includes('listImageFiles') && service.includes('deployImageFile'), 'simple file APIs must be used')
assert.ok(!service.includes('X-Chunk-SHA256'), 'new uploads must not calculate chunk SHA-256')
assert.ok(view.includes('镜像文件') && view.includes('推送进度') && view.includes('服务器清单'), 'three operational views are required')
assert.ok(!view.includes('审核') && !view.includes('发布版本') && !view.includes('导入进度'), 'legacy workflow controls must be removed')
assert.ok(view.includes('latestMetrics') && view.includes('containers') && view.includes('images'), 'server inventory must be visible')
assert.ok(upload.includes('FILE_EXISTS') && upload.includes('确认覆盖'), 'existing canonical files require one confirmation')
assert.ok(upload.includes('accept=".tar"') && !upload.includes('SHA-256'), 'upload accepts TAR without SHA UI')
assert.ok(deployment.includes('同名镜像') && deployment.includes('overwrite'), 'same-name images require overwrite confirmation')
assert.ok(deployment.includes('listProcessingAgents'), 'deployment targets processing Agents')
assert.ok(upload.includes("this.$emit('uploaded', upload); this.close(true)"), 'successful upload must close its dialog')
assert.ok(view.includes('async uploaded (upload)') && view.includes('this.uploadVisible = false'), 'successful upload must immediately close and refresh the page')
assert.ok(view.includes('<el-progress') && view.includes('progressPercent') && view.includes('transferredBytes') && view.includes('totalBytes'), 'deployment rows must show live transfer progress')
for (const rendered of [view, upload, deployment]) assert.ok(!/password|credential|authorization|rawPayload/i.test(rendered), 'secrets must not be rendered')
console.log('simple image delivery UI contract tests passed')
