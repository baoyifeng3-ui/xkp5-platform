const fs = require('fs')
const dialog = fs.readFileSync('src/components/operations/ImageUploadDialog.vue', 'utf8')
const api = fs.readFileSync('src/services/imageRegistry.js', 'utf8')

for (const token of ['uploadImageFile', 'FILE_EXISTS', '确认覆盖']) if (!dialog.includes(token)) throw new Error(`direct upload contract missing ${token}`)
if (dialog.includes('resumeUpload') || dialog.includes('getImageUploadByArtifact') || dialog.includes('uploadImageChunk')) throw new Error('direct upload must use one request')
if (!api.includes('silentError: true')) throw new Error('upload creation must surface overwrite decisions locally')
if (/data\.append\('(repository|tag)'/.test(dialog) || /v-model\.trim="(repository|tag)"/.test(dialog)) throw new Error('upload must only request a file, with identity derived by the backend')
if (!dialog.includes("error === 'cancel' || error === 'close'")) throw new Error('declining overwrite must not report an upload failure')
console.log('direct image upload retry contract passed')
