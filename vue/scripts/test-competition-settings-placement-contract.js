const assert = require('assert')
const fs = require('fs')

const source = fs.readFileSync('src/views/Admin.vue', 'utf8')
const rulesStart = source.indexOf('<el-tab-pane name="rules">')
const subjectsStart = source.indexOf('<el-tab-pane name="subjects">')
const usersStart = source.indexOf('<el-tab-pane name="users">')
const gradingStart = source.indexOf('<el-tab-pane name="grading">')
const rules = source.slice(rulesStart, subjectsStart)
const users = source.slice(usersStart)

assert.ok(rules.includes('注意事项'))
assert.ok(rules.includes('比赛公告字段'))
assert.ok(rules.includes('label="比赛公告"'))
assert.ok(rules.includes('announcementValue'))
assert.ok(rules.includes('label="注意事项"'))
assert.ok(rules.includes('announcementEntries'))
assert.ok(rules.includes('新增条目'))
assert.ok(rules.includes('editAnnouncementEntry'))
assert.ok(!rules.includes('participantUsers'))
assert.ok(!users.slice(0, users.indexOf('<div class="summary-band"')).includes('注意事项'))
assert.ok(gradingStart < usersStart)
assert.ok(source.includes('.admin-tabs::v-deep > .el-tabs__header { display: none; }'))

console.log('competition settings placement contract tests passed')
