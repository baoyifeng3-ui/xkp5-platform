const assert = require('assert')
const fs = require('fs')

const api = fs.readFileSync('src/api/PlatformMode.js', 'utf8')
const home = fs.readFileSync('src/views/management/ManagementHome.vue', 'utf8')
const router = fs.readFileSync('src/router/index.js', 'utf8')
const navigation = fs.readFileSync('src/navigation/roleNavigation.js', 'utf8')

assert.ok(api.includes('getPlatformMode'))
assert.ok(api.includes('changePlatformMode'))
assert.ok(api.includes('listModeTransitions'))
assert.ok(api.includes('getModeTransition'))
assert.ok(!router.includes("path: 'competition-mode'"), 'dedicated mode route must be deleted')
assert.ok(!router.includes('import CompetitionMode'), 'deleted mode page must not be imported')
assert.ok(!navigation.includes('模式与环境'), 'mode menu item must be removed')
assert.ok(!navigation.includes("label: '比赛环境'"), 'competition environment menu must be removed')
assert.ok(/import\s*\{\s*getPlatformMode,\s*changePlatformMode\s*\}\s*from\s*["']@\/api\/PlatformMode["']/.test(home))
assert.ok(/platformMode\s*===\s*["']COMPETITION["']\s*\?\s*["']退出比赛模式["']\s*:\s*["']进入比赛模式["']/.test(home))
assert.ok(home.includes('togglePlatformMode'))
assert.ok(home.includes('changePlatformMode(target)'))
assert.ok(api.includes("'Content-Type': 'application/json'"), 'mode changes must use JSON')
assert.ok(home.includes('this.$confirm'))
assert.ok(!home.includes('this.$prompt'))
assert.ok(home.includes('普通用户现有登录会失效'))
assert.ok(!api.includes('confirmation:'), 'mode API must not send confirmation phrases')
assert.ok(home.includes('CLASS_SERVERS_OFFLINE'), 'offline servers must trigger a confirmation flow')
assert.ok(home.includes('ignoreOffline'), 'confirmed class start must allow queued offline servers')
assert.ok(home.includes('getClassTrainingStatus'), 'class readiness must be polled')
assert.ok(home.includes('课堂环境已全部就绪'), 'server recovery must notify the administrator')
assert.ok(home.includes('syncPlatformMode'), 'dashboard must synchronize the persisted mode into the global session')
assert.ok(home.indexOf('await getPlatformMode()') < home.indexOf('Promise.all(['), 'dashboard must read mode before mode-specific requests')
assert.ok(home.includes("this.platformMode === \"TRAINING\""), 'dashboard must skip training-only requests in competition mode')
assert.ok(home.includes('getUserInfo'), 'dashboard mode synchronization must update persisted user state')
assert.ok(!home.includes('<h1>工作台</h1>'), 'large dashboard title must be removed')

console.log('management mode contract tests passed')
